-- Para poder rodar o script mais de uma vez do zero
DROP VIEW  IF EXISTS vw_ranking;
DROP TABLE IF EXISTS respostas_partida CASCADE;
DROP TABLE IF EXISTS partidas          CASCADE;
DROP TABLE IF EXISTS alternativas      CASCADE;
DROP TABLE IF EXISTS perguntas         CASCADE;
DROP TABLE IF EXISTS jogadores         CASCADE;

-- ------------------------------------------------------------
-- JOGADORES
-- Hoje o login só pede o nome (campo nomeJogador).
-- ------------------------------------------------------------
CREATE TABLE jogadores (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  nome       VARCHAR(60) NOT NULL,
  criado_em  TIMESTAMP   NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ------------------------------------------------------------
-- PERGUNTAS
-- Antes ficavam no array "perguntas" do quiz.js.
-- ------------------------------------------------------------
CREATE TABLE perguntas (
  id         INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enunciado  VARCHAR(500) NOT NULL,
  ativa      BOOLEAN      NOT NULL DEFAULT TRUE
);

-- ------------------------------------------------------------
-- ALTERNATIVAS
-- 4 por pergunta (A, B, C, D). "ordem" 0..3 equivale ao índice
-- do array "alternativas" do quiz.js. "correta" substitui o
-- antigo campo "resposta".
-- ------------------------------------------------------------
CREATE TABLE alternativas (
  id           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pergunta_id  INTEGER      NOT NULL REFERENCES perguntas (id) ON DELETE CASCADE,
  ordem        SMALLINT     NOT NULL CHECK (ordem BETWEEN 0 AND 3),
  texto        VARCHAR(300) NOT NULL,
  correta      BOOLEAN      NOT NULL DEFAULT FALSE,
  CONSTRAINT uq_pergunta_ordem UNIQUE (pergunta_id, ordem)
);

-- ------------------------------------------------------------
-- PARTIDAS
-- Cada vez que alguém termina o quiz. Substitui o item do
-- localStorage "codequestRanking" {nome, pontos, total, data}.
-- ------------------------------------------------------------
CREATE TABLE partidas (
  id               INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  jogador_id       INTEGER   NOT NULL REFERENCES jogadores (id) ON DELETE CASCADE,
  pontos           SMALLINT  NOT NULL CHECK (pontos >= 0),
  total_perguntas  SMALLINT  NOT NULL CHECK (total_perguntas > 0),
  data_partida     TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_partidas_ranking ON partidas (pontos DESC, data_partida ASC);

-- ------------------------------------------------------------
-- RESPOSTAS DA PARTIDA
-- O que o jogador marcou em cada pergunta. Permite mostrar
-- estatísticas (ex.: pergunta mais errada).
-- ------------------------------------------------------------
CREATE TABLE respostas_partida (
  id                        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  partida_id                INTEGER NOT NULL REFERENCES partidas (id) ON DELETE CASCADE,
  pergunta_id               INTEGER NOT NULL REFERENCES perguntas (id),
  alternativa_escolhida_id  INTEGER NOT NULL REFERENCES alternativas (id),
  acertou                   BOOLEAN NOT NULL,
  CONSTRAINT uq_partida_pergunta UNIQUE (partida_id, pergunta_id)
);

-- ------------------------------------------------------------
-- RANKING (mesma regra do ranking.js: mais pontos primeiro,
-- empate vai para quem jogou antes; top 10)
-- ------------------------------------------------------------
CREATE VIEW vw_ranking AS
SELECT
  j.nome,
  p.pontos,
  p.total_perguntas,
  p.data_partida
FROM partidas p
JOIN jogadores j ON j.id = p.jogador_id
ORDER BY p.pontos DESC, p.data_partida ASC
LIMIT 10;

